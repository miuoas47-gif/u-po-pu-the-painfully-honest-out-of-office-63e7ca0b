#!/usr/bin/env python3
"""The Painfully Honest Out-of-Office.

Prints exactly one original funny line, deterministically.
"""

LINE = (
    "I'm out of the office and will not be checking email, which is a lie — "
    "I will check it constantly, answer nothing, and return twice as stressed."
)


